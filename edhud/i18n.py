def language_from_langids(langids: list[int], platform: str = "win32") -> str:
    """Русский только на русской Windows. Иначе английский."""
    if platform != "win32":
        return "en"
    for langid in langids:
        try:
            if (int(langid) & 0x3FF) == LANG_RUSSIAN:
                return "ru"
        except (TypeError, ValueError):
            continue
    return "en"


def _windows_langids() -> list[int]:
    import ctypes

    kernel = ctypes.windll.kernel32
    found: list[int] = []
    for name in ("GetUserDefaultUILanguage", "GetUserDefaultLangID", "GetSystemDefaultUILanguage"):
        fn = getattr(kernel, name, None)
        if fn is None:
            continue
        try:
            found.append(int(fn()))
        except (OSError, ValueError):
            continue
    return found


def detect_language() -> str:
    forced = os.environ.get("EDHUD_LANG", "").strip().lower()
    if forced in ("ru", "en"):
        return forced
    if sys.platform != "win32":
        return "en"
    try:
        return language_from_langids(_windows_langids(), "win32")
    except (OSError, AttributeError):
        return "en"


def language() -> str:
    global _LANG
    forced = os.environ.get("EDHUD_LANG", "").strip().lower()
    if forced in ("ru", "en"):
        _LANG = forced
        return forced
    if _LANG not in ("ru", "en"):
        _LANG = detect_language()
    return _LANG


def set_language(lang: str) -> None:
    """Принудительный язык (настройки / тесты)."""
    global _LANG
    _LANG = "ru" if str(lang).lower().startswith("ru") else "en"
    os.environ["EDHUD_LANG"] = _LANG


def clear_language_override() -> None:
    """Сбросить принудительный язык — снова брать из Windows / EDHUD_LANG."""
    global _LANG
    _LANG = None
    os.environ.pop("EDHUD_LANG", None)


def apply_config_language(lang: str | None) -> str:
    """Применить язык из config.json. Пусто = автодетект ОС."""
    value = (lang or "").strip().lower()
    if value in ("ru", "en"):
        set_language(value)
        return value
    clear_language_override()
    return language()


def t(key: str, **kwargs) -> str:
    lang = language()
    table = _STRINGS.get(lang) or _STRINGS["en"]
    text = table.get(key)
    if text is None:
        text = _STRINGS["en"].get(key, key)
    if kwargs:
        return text.format(**kwargs)
    return text


def jumps_word(count: int) -> str:
    n = abs(int(count))
    if language() != "ru":
        return t("jump.one") if n == 1 else t("jump.many")
    mod100 = n % 100
    if 11 <= mod100 <= 14:
        return t("jump.many")
    last = n % 10
    if last == 1:
        return t("jump.one")
    if 2 <= last <= 4:
        return t("jump.few")
    return t("jump.many")
