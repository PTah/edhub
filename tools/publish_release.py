import subprocess
import sys

NOTES = """**1.7.2: окно «Биосигналы» больше не висит без запущенной игры, таблица стала «Сводкой»**

- Причина была в том, что «игра запущена» определялось по журналу: он
  заканчивается `Shutdown` только при аккуратном выходе, поэтому после
  закрытия игры EDHUD продолжал считать, что сессия идёт, и показывал био-панель
  со старыми данными. Теперь свежесть проверяется по `Status.json` (игра пишет
  его каждую секунду): старше трёх минут — считаем, что игра не запущена.
- Пока игра не запущена или открыто главное меню: верхний дашборд не виден
  (alpha 0), окно «Биосигналы» скрыто. На поверхности планеты, в ТРП и пешком
  дашборд приглушается (0.10), био-панель остаётся.
- Первый вызов приглушения на старте теперь всегда применяется (раньше
  «состояние уже false» могло оставить панели как есть).
- Главное окно с таблицей получило имя **«Сводка»**: заголовок
  «EDHUD — сводка», в трее — «Сводка: Route / Bodies / Пояса / Добыча».
- README: разделы про прозрачность и окна обновлены.

Версия 1.7.2. Тесты: 295 passed."""

ASSETS = [
    r"dist\EDHUD-portable-1.7.2.zip",
    r"dist\EDHUD-1.7.2-windows.zip",
    r"dist\EDHUD-Setup-1.7.2.exe",
]

cmd = ["gh", "release", "create", "v1.7.2", *ASSETS, "--repo", "PTah/edhub",
       "--title", "EDHUD 1.7.2", "--notes", NOTES]
result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
print("exit:", result.returncode)
print(result.stdout.strip())
print(result.stderr.strip())
sys.exit(result.returncode)
