import subprocess
import sys

NOTES = """**1.7.4: статистика сессии больше не приписывает себе прошлые продажи**

- Причина: при смене файла журнала (новый вход в игру) счётчики сессии в
  состоянии игры **не обнулялись**. Игра начинала новую сессию, а EDHUD тащил
  в неё продажи, сканы и ly предыдущей — отсюда «187 млн продано» в сессии, где
  не продано ничего, и завышенные итоги.
- Теперь новая сессия начинается по событию `Fileheader` (оно есть в начале
  каждого журнала), а время начала берётся из отметки времени игры. Счётчики
  прыжков, сканов, DSS, био-анализов, выработки и продаж обнуляются.
- Начало сессии в таблице берётся из имени журнала
  (`Journal.2026-11-15T191923.01.log` → 19:19), а не из времени запуска EDHUD:
  раньше из-за этого две разные сессии показывали одно и то же время.
- При загрузке база чинится автоматически: время сессий восстанавливается по
  именам журналов, дубли одной сессии схлопываются.
- На вкладке «Статистика» появились кнопки:
  **«Пересобрать из журналов»** — пересчитать всю историю по файлам журналов
  (точные цифры задним числом, фоном, с прогрессом) и **«Сбросить статистику»**.
- Тесты: 307 passed (обнуление сессии, время из имени журнала, пересборка).

Версия 1.7.4."""

ASSETS = [
    r"dist\EDHUD-portable-1.7.4.zip",
    r"dist\EDHUD-1.7.4-windows.zip",
    r"dist\EDHUD-Setup-1.7.4.exe",
]

cmd = ["gh", "release", "create", "v1.7.4", *ASSETS, "--repo", "PTah/edhub",
       "--title", "EDHUD 1.7.4", "--notes", NOTES]
result = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
print("exit:", result.returncode)
print(result.stdout.strip())
